import puppeteer from 'puppeteer-core'
import { mkdtemp, mkdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import express from 'express'
import assert from 'node:assert/strict'
import { createApp } from '../server/app.mjs'

const dataDir = await mkdtemp(join(tmpdir(), 'skillscope-browser-'))
const { app } = await createApp({ dataDir, communityFetcher: async () => ({ skills: [{ source: 'owner/repo', skillId: 'example', name: 'example', installs: 123, url: 'https://skills.sh/owner/repo/example' }], totalSkills: 1, fetchedAt: new Date().toISOString(), source: 'https://skills.sh/', stale: false }) })
app.use(express.static('dist'))
app.use((_req, res) => res.sendFile(join(process.cwd(), 'dist', 'index.html')))
const server = app.listen(0, '127.0.0.1')
await new Promise(resolve => server.once('listening', resolve))
const base = 'http://127.0.0.1:' + server.address().port
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const text = async () => page.evaluate(() => document.body.innerText)
const clickText = async (selector, target) => {
  const match = await page.$$(selector)
  for (const element of match) {
    if ((await element.evaluate(el => el.textContent)).trim().includes(target)) { await element.click(); return }
  }
  throw new Error('未找到操作：' + target)
}
try {
  await mkdir('.qa', { recursive: true })
  await page.setViewport({ width: 1440, height: 1000, deviceScaleFactor: 1 })
  await page.goto(base, { waitUntil: 'networkidle0' })
  await page.waitForSelector('.skill-card')
  assert.equal(await page.$$('.skill-card').then(items => items.length), 8)
  await page.screenshot({ path: '.qa/desktop.png', fullPage: true })
  await page.type('.global-search input', 'Data Storyteller')
  await page.waitForFunction(() => document.querySelectorAll('.skill-card').length === 1)
  assert.match(await text(), /Data Storyteller/)
  await page.$eval('.global-search input', el => { el.value = ''; el.dispatchEvent(new Event('input', { bubbles: true })) })
  await page.reload({ waitUntil: 'networkidle0' })
  await page.waitForSelector('.skill-card')
  await clickText('.category-tabs button', '开发工具')
  assert.equal(await page.$$('.skill-card').then(items => items.length), 3)
  await clickText('.category-tabs button', '全部')
  await page.click('.skill-card .bookmark-button')
  await page.click('a[href="/favorites"]')
  await page.waitForFunction(() => location.pathname === '/favorites')
  assert.equal(await page.$$('.skill-card').then(items => items.length), 1)
  await page.goto(base, { waitUntil: 'networkidle0' })
  await page.waitForSelector('.skill-card')
  const compareButtons = await page.$$('.skill-card .compare-add')
  await compareButtons[0].click()
  await compareButtons[1].click()
  await page.click('.compare-float')
  await page.waitForSelector('.comparison-table')
  assert.equal(await page.$$('.compare-item').then(items => items.length), 2)
  await page.click('.side-link[href="/rankings"]')
  await page.waitForSelector('.community-row')
  assert.equal(await page.$$('.community-row').then(items => items.length), 1)
  assert.match(await text(), /累计安装量/)
  await page.click('.side-link[href="/methodology"]')
  await page.waitForSelector('.method-dimensions')
  assert.match(await text(), /不能证明安全性/)
  await page.click('.top-submit')
  await page.waitForSelector('.modal textarea')
  await page.type('.modal textarea', '---\nname: browser-check\ndescription: Use when checking browser interaction and producing a structured report.\n---\n\n# Browser Check\n\n## 适用场景\n当用户需要查看报告时使用。\n\n## 工作流程\n1. 输入问题。\n2. 分析输入。\n3. 验证输出。\n\n## 边界与安全\n不读取密钥，覆盖前确认。')
  await clickText('.modal .primary-button', '开始评测')
  await page.waitForSelector('.dimension-detail', { timeout: 15000 })
  await page.waitForSelector('.modal-overlay', { hidden: true })
  assert.match(await text(), /browser-check/)
  assert.match(await text(), /评测内容/)
  await clickText('.dimension-tabs button','安全性')
  await page.waitForFunction(() => document.querySelector('.dimension-head')?.textContent.includes('安全边界'))
  assert.match(await page.$eval('.dimension-head', el => el.textContent), /安全边界/)
  await page.screenshot({ path: '.qa/report.png', fullPage: true })
  await page.reload({ waitUntil:'networkidle0' })
  assert.match(await text(), /browser-check/)
  await page.goto(base, { waitUntil: 'networkidle0' })
  await page.click('.top-submit')
  await clickText('.modal-tabs button', 'GitHub')
  await page.type('.github-input input', 'https://example.com/test')
  await page.click('.import-button')
  await page.waitForSelector('.form-error')
  assert.match(await page.$eval('.form-error', el => el.textContent), /仅支持/)
  await page.click('.modal-heading .icon-button')
  await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1 })
  await page.goto(base, { waitUntil:'networkidle0' })
  await page.waitForSelector('.skill-card')
  const overflow = await page.evaluate(() => ({ body: document.documentElement.scrollWidth, viewport: innerWidth }))
  assert.ok(overflow.body <= overflow.viewport, '移动端发生水平溢出 ' + JSON.stringify(overflow))
  await page.screenshot({ path: '.qa/mobile.png', fullPage:true })
  await page.click('.menu-button')
  assert.ok(await page.$('.sidebar.sidebar-open'))
  await page.waitForFunction(() => document.querySelector('.mobile-close')?.getBoundingClientRect().x > 0)
  await page.click('.mobile-close')
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log('浏览器验证通过：发现、搜索、筛选、收藏、对比、榜单、评分方法、提交、报告、持久化、导入错误和移动端布局。')
} finally {
  await browser.close()
  await new Promise(resolve => server.close(resolve))
  await rm(dataDir, { recursive: true, force: true })
}
